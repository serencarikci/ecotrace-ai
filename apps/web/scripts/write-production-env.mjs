#!/usr/bin/env node
/**
 * Write production environment.apiUrl from ECOTRACE_API_URL (or API_URL).
 * Does not print secrets. Safe for CI / Vercel build steps.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(__dirname, '../src/environments/environment.production.ts');
const raw = (process.env.ECOTRACE_API_URL || process.env.API_URL || '').trim().replace(/\/$/, '');

if (raw && !/^https:\/\//i.test(raw) && process.env.ALLOW_NON_HTTPS_API_URL !== 'true') {
  console.error('ECOTRACE_API_URL must be an https:// origin for external builds');
  process.exit(1);
}
if (/localhost|127\.0\.0\.1/i.test(raw)) {
  console.error('ECOTRACE_API_URL must not point at localhost for production builds');
  process.exit(1);
}

const apiUrlLiteral = JSON.stringify(raw);
const contents = `/**
 * Generated by scripts/write-production-env.mjs — do not commit secrets.
 */
export const environment = {
  production: true,
  apiUrl: ${apiUrlLiteral},
  apiV1Prefix: '/api/v1',
  appVersion: '0.7.1',
};
`;
fs.writeFileSync(target, contents, 'utf8');
console.log('wrote environment.production.ts apiUrl=', raw ? '[set]' : '[empty-same-origin]');
